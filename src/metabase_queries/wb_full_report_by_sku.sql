-- Metabase: "Таблица - Полный отчет Wb по артикулу" — native SQL question
-- поверх "Модель - WB метрики по кабинету, артикулу и месяцу" (см.
-- wb_metrics_model_sku.sql). Wide-формат (одна строка = кабинет+артикул+
-- месяц, колонки = все 19 метрик модели), а не unpivot+pivot, как у
-- wb_metrics_by_month.sql/"Визуал - Полный отчет Wb" — с добавлением
-- измерения "Артикул" unpivot-подход даёт неудобно много строк и не нужен:
-- этот отчёт открывают, уже выбрав конкретный кабинет+артикул через
-- дашборд-фильтры, а не листают общий свод.
--
-- {{cabinet}}/{{sku}} — простые текстовые переменные (точное совпадение),
-- НЕ Field Filter — тот же паттерн, что и в остальных native SQL карточках
-- проекта (см. wb_metrics_by_month.sql, reconciliation-таблицы). Оба
-- фильтра опциональны на уровне SQL ([[...]]), но на дашборде
-- "Дашборд - WB Полный отчёт по артикулу" помечены обязательными — без
-- них таблица покажет все кабинеты/артикулы разом, что для этого отчёта
-- малополезно (хотя, в отличие от pivot-агрегации, ничего не просуммирует
-- неверно — каждая строка остаётся отдельной).
--
-- {{#<id модели>}} — плейсхолдер card-ссылки, id проставляется при
-- создании карточки в Metabase, здесь не хардкожен.

SELECT *
FROM {{#wb_metrics_model_sku}}
WHERE 1=1
[[AND "Кабинет" = {{cabinet}}]]
[[AND "Артикул продавца" = {{sku}}]]
ORDER BY "Месяц" DESC
