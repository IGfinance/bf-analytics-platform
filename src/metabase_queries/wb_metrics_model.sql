-- Metabase: "Модель - WB метрики по кабинету и месяцу" (id 49 в проде на
-- 2026-09-03, см. dashboards.finance-black.ru — id меняется, если модель
-- пересоздать заново, сверяйтесь по имени, а не по id).
--
-- Источник истины для отчётных метрик WB (продажи, логистика, штрафы,
-- программа лояльности и т.д.). Остальные Metabase-карточки должны
-- ссылаться на эту модель через конструктор запросов или {{#<id>}} в
-- native SQL, а не копировать формулы заново — см. «Один источник истины
-- для формул» в .claude/knowledge/architecture-standarts.md и инцидент
-- 2026-09-03 в чёрном списке антипаттернов там же.
--
-- С 2026-09-05 сами формулы здесь БОЛЬШЕ НЕ считаются — они переехали в
-- ClickHouse VIEW `wb_metrics_by_cabinet_month` (см. `../schema_wb_metrics_views.sql`),
-- чтобы формула была видна и достижима не только из Metabase, но и из
-- любого другого потребителя ClickHouse — в первую очередь из будущего
-- AI-бота, если он будет писать ad-hoc SQL напрямую к базе. Правьте формулы
-- в VIEW, а не здесь — см. «Семантический слой для AI-бота» в
-- .claude/knowledge/architecture-standarts.md.
--
-- Эта модель — тонкая обёртка: переименовывает технические колонки VIEW в
-- русские подписи для дашборда.
--
-- С 2026-09-23 добавлены "Себестоимость" и "Валовая прибыль" (= "К
-- перечислению итого" + себестоимость, которая хранится со знаком минус),
-- а рядом с ними — две служебные счётные колонки "Ед. с себестоимостью"/
-- "Ед. без себестоимости". Вторая пара нужна, чтобы было видно, на сколько
-- себестоимость занижена: у артикулов, которых нет в справочнике
-- wb_cogs_weekly, себестоимость считается нулевой (решение пользователя
-- 2026-09-23). Долю покрытия считайте в карточке как
-- covered/(covered+uncovered) — готовой колонки-процента нет намеренно,
-- такую долю нельзя суммировать по месяцам.
--
-- Field Filter по кабинету сюда НЕ добавлен (проверено на проде
-- 2026-09-05): Metabase запрещает переменные/Field Filter в Модели,
-- созданной из native SQL ("Модель, созданная из вопроса на нативном
-- SQL, не может иметь переменную или фильтр по полю"). Фильтрация по
-- кабинету на дашборде — отдельная задача, требует варианта (а) из
-- wb_metrics_by_month.sql (пересобрать 40/42 как GUI-question поверх
-- этой модели).

SELECT
    cabinet                          AS "Кабинет",
    month                             AS "Месяц",
    sales_qty                        AS "Кол-во продаж",
    sales_amount                     AS "Продажи",
    spp_amount                       AS "СПП",
    wb_commission                    AS "Комиссия ВБ",
    payable_for_goods                AS "К перечислению за товар",
    logistics_direct                 AS "Логистика прямая",
    logistics_reverse                AS "Логистика обратная",
    fines                            AS "Штрафы",
    commission_correction            AS "Доплаты",
    storage_cost                     AS "Хранение",
    acceptance_cost                  AS "Платная приемка",
    deductions                       AS "Удержание",
    wibes_discount                   AS "Скидка Wibes",
    promotion_cost                   AS "Продвижение WB",
    payable_total                    AS "К перечислению итого",
    cogs                             AS "Себестоимость",
    gross_profit                     AS "Валовая прибыль",
    cogs_qty_covered                 AS "Ед. с себестоимостью",
    cogs_qty_uncovered               AS "Ед. без себестоимости"
FROM wb_metrics_by_cabinet_month
ORDER BY cabinet, month
