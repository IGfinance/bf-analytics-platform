-- Metabase: native SQL карточек "Таблица - Метрики для отчета Wb" (id 40) и
-- "Таблица - Полный отчет Wb" (id 42) — обе идентичны с 2026-09-03, обе
-- разворачивают "Модель - WB метрики по кабинету и месяцу" (см.
-- wb_metrics_model.sql) в long-формат (строка = метрика), нужный для
-- Metabase pivot table (visual-карточки "Визуал - ..." строят breakout по
-- колонкам metric/month поверх этого).
--
-- {{#49}} — Metabase-плейсхолдер card-ссылки на модель. Это НЕ переносимый
-- SQL: если модель пересоздать, id изменится и текст карточки в Metabase
-- нужно поправить руками (этот файл — документация того, что должно быть
-- в Metabase, не то, что можно скопипастить в консоль ClickHouse — для
-- прямого запуска см. wb_metrics_model.sql, он самодостаточный).
--
-- До 2026-09-03 карточки 40 и 42 пересчитывали формулы метрик независимо
-- друг от друга (и от reconciliation_rules_wb.yaml) — см. инцидент 2026-09-03
-- в .claude/knowledge/architecture-standarts.md. Теперь обе читают из одной
-- модели, разночтений между панелями дашборда быть не должно.
--
-- Дата "заякорена" на 12:00 (INTERVAL 12 HOUR) внутри модели, а не 00:00 —
-- иначе Report Timezone в Metabase сдвигает 1-е число месяца на последний
-- день предыдущего (28/29/30/31).
--
-- ВАЖНО (баг, исправленный 2026-09-05): раньше эта карточка не выводила
-- "Кабинет" вообще — при нескольких кабинетах строки {{#49}} с одинаковым
-- (месяц, метрика) молча складывались в pivot-таблице Metabase, и дашборд
-- показывал сумму по ВСЕМ кабинетам без какой-либо возможности отфильтровать
-- один. Сейчас "Кабинет" — часть SELECT, это даёт breakout по кабинету на
-- визуал-карточках сверху и делает баг видимым, если кто-то забудет
-- сгруппировать/отфильтровать.
--
-- Прокинуть dashboard-фильтр "Кабинет" через {{#49}} в эту карточку
-- напрямую нельзя (Field Filter модели не пробрасывается транзитивно через
-- вложенный {{#id}} на её алиас "Кабинет"). Два рабочих варианта, выбрать
-- в самом Metabase:
--   (а) [рекомендуется] пересобрать 40/42 как GUI-question поверх модели
--       49 (конструктор запросов, не native SQL) — тогда dashboard-фильтр
--       по кабинету работает "из коробки" через биндинг полей;
--   (б) оставить native SQL, но добавить эту карточку своей переменной
--       {{cabinet}} с [[AND "Кабинет" = {{cabinet}}]] в каждой ветке UNION —
--       расходы на поддержку выше, чем у варианта (а).

SELECT * FROM (
SELECT "Месяц" AS month, "Кабинет" AS cabinet, '01 Кол-во продаж' AS metric, toFloat64("Кол-во продаж") AS value FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '02 Продажи + СПП', toFloat64("Продажи" + "СПП") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '03 Продажи', toFloat64("Продажи") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '04 СПП', toFloat64("СПП") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '05 Комиссия ВБ', toFloat64("Комиссия ВБ") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '06 К перечислению за товар', toFloat64("К перечислению за товар") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '07 Логистика', toFloat64("Логистика прямая" + "Логистика обратная") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '07.01 Логистика прямая', toFloat64("Логистика прямая") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '07.02 Логистика обратная', toFloat64("Логистика обратная") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '08 Штрафы', toFloat64("Штрафы") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '09 Доплаты', toFloat64("Доплаты") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '10 Хранение', toFloat64("Хранение") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '11 Платная приемка', toFloat64("Платная приемка") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '12 Удержание', toFloat64("Удержание") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '13 Скидка Wibes', toFloat64("Скидка Wibes") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '14 Продвижение WB', toFloat64("Продвижение WB") FROM {{#49}}
UNION ALL SELECT "Месяц", "Кабинет", '15 К перечислению', toFloat64("К перечислению итого") FROM {{#49}}
)
ORDER BY month, cabinet, metric
