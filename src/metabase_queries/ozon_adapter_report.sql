-- Metabase: "Визуал - CloudSix - Отчет для адаптера Ozon" (id 64 на 2026-09-23).
-- Лежит на дашборде "01 Дашборд - CloudSix - Адаптеры" (id 2).
--
-- С 2026-09-23 карточка переделана из pivot-визуала в ПЛОСКУЮ широкую
-- выгрузку: одна строка = кабинет за месяц, показатели разложены по
-- столбцам в том же порядке и с той же нумерацией (01…17), что в отчётах
-- по артикулам. Колонка "Площадка" константна внутри карточки ('Ozon') и
-- нужна, чтобы выгрузки по WB и Ozon можно было сложить в одну таблицу —
-- ради этого же совпадает и порядок первых трёх колонок.
--
-- Формулы не дублируются: карточка читает готовые колонки Модели 62
-- через {{#62}} (см. ozon_metrics_model.sql).
--
-- Фильтр "Кабинет" на дашборде привязан ЧЕРЕЗ ПЕРЕМЕННУЮ
-- ["variable", ["template-tag", "cabinet"]], а не через ["dimension", ...]:
-- у native SQL это единственный рабочий путь, dimension-таргет молча
-- перестаёт фильтровать (та же гочтя, что описана в
-- .claude/knowledge/architecture-standarts.md). До переделки карточка была
-- MBQL-пивотом, и таргет был dimension — при переходе маппинг на дашборде
-- пришлось переписать.
--
-- Формально это карточка-Таблица на дашборде, то есть исключение из правила
-- "на дашборде только Визуалы" (см. architecture-standarts.md). Исключение
-- осознанное: карточка существует как выгрузка для внешнего адаптера, а не
-- как визуализация для чтения глазами. Имя оставлено с префиксом "Визуал -",
-- потому что это то, что реально выведено на дашборд.

-- ПРАВКА 2026-10-04: добавлен столбец «Бренд» после «Кабинета» (карточка 64). Бренд — из каталога Ozon
-- (ozon_products, атрибут «Бренд») по артикулу; пустой и «Нет бренда» = название кабинета, CloudSix = «Cloud Six».
-- Строка = кабинет × бренд × месяц. Привязанное к артикулу лежит на бренде ТОЧНО; расходы кабинета (строки
-- без артикула) РАЗЛОЖЕНЫ по брендам пропорционально выручке бренда за месяц — это оценка, а не данные Ozon.
-- Сумма по брендам = прежняя строка кабинета (проверено на данных). Вьюхи: scripts/gen_ozon_brand_views.py.
-- Карточка читает ozon_metrics_by_cabinet_brand_month напрямую, а не Модель 62 (бренда в модели нет, она не менялась).
SELECT
    "Месяц"                                                AS "Месяц",
    "Кабинет"                                               AS "Кабинет",
    "Бренд"                                                  AS "Бренд",
    'Ozon'                                                   AS "Площадка",
    toFloat64("Кол-во продаж")                                AS "01 Кол-во продаж",
    toFloat64("Выручка + СПП")                                 AS "02 Выручка + СПП",
    toFloat64("Выручка")                                        AS "03 Выручка",
    toFloat64("СПП")                                             AS "04 СПП",
    toFloat64("Комиссия")                                         AS "05 Комиссия",
    toFloat64("Корректировки, брак, потери и возвраты")            AS "06 Корректировки, брак, потери и возвраты",
    toFloat64("К перечислению за товар")                            AS "07 К перечислению за товар",
    toFloat64("Логистика")                                           AS "08 Логистика",
    toFloat64("Последняя миля")                                       AS "09 Последняя миля",
    toFloat64("Штрафы")                                                AS "10 Штрафы",
    toFloat64("Доплаты")                                                AS "11 Доплаты",
    toFloat64("Хранение на складе")                                      AS "12 Хранение на складе",
    toFloat64("Продвижение")                                              AS "13 Продвижение",
    toFloat64("Прочие начисления")                                         AS "14 Прочие начисления",
    toFloat64("Выручка к перечислению")                                     AS "15 Выручка к перечислению",
    toFloat64("Себестоимость")                                               AS "16 Себестоимость",
    toFloat64("Валовая прибыль")                                              AS "17 Валовая прибыль"
FROM (
SELECT
    cabinet             AS "Кабинет",
    brand                AS "Бренд",
    month                 AS "Месяц",
    sales_qty             AS "Кол-во продаж",
    sales_with_spp        AS "Выручка + СПП",
    sales_amount          AS "Выручка",
    spp_amount            AS "СПП",
    commission            AS "Комиссия",
    returns_corrections   AS "Корректировки, брак, потери и возвраты",
    payable_for_goods     AS "К перечислению за товар",
    logistics_cost        AS "Логистика",
    last_mile_cost        AS "Последняя миля",
    fines                 AS "Штрафы",
    surcharges            AS "Доплаты",
    storage_cost          AS "Хранение на складе",
    promotion_cost        AS "Продвижение",
    other_accruals        AS "Прочие начисления",
    payable_total         AS "Выручка к перечислению",
    cogs                  AS "Себестоимость",
    gross_profit          AS "Валовая прибыль"
FROM ozon_metrics_by_cabinet_brand_month
) AS m
WHERE 1 = 1
[[AND "Кабинет" = {{cabinet}}]]
ORDER BY "Месяц", "Кабинет", "Бренд"
