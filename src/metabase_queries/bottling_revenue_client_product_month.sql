-- Metabase: "Визуал - Bottling - Выручка клиент, продукция, месяц"
-- Плоская таблица для проверки и выгрузки: одна строка = клиент (юрлицо-контрагент) x продукция
-- (номенклатура) x месяц, значение — выручка БЕЗ НДС в рублях. Коллекция "Bottling | Админка" (15).
-- Дашборд: "02 Дашборд - Bottling - Выручка клиент, продукция, месяц".
--
-- Источник — VIEW bottling.realization_revenue, тот же, что у "Визуал - Bottling - Выручка по компаниям
-- и месяцам" (id 209) и дашборда 16: проведённые документы, без пометки удаления, amount = без НДС
-- (amount_with_vat — с НДС, здесь не используется). Возвраты НЕ вычитаются (как и в дашборде 16):
-- это продажи по реализациям.
--
-- Фильтры (Field Filter на поля VIEW, как в дашборде 16): Компания=counterparty, Продукт=nomenclature,
-- Период=month. Период по умолчанию "после 2025-12-31" (= с 01.01.2026, ~1200 строк).
-- ГОЧТЯ: открытый диапазон "ДАТА~" Metabase превращает в month > ДАТА (строго после), поэтому
-- для периода "с 01.01.2026" задаётся 2025-12-31~, иначе январь выпадает целиком.
-- В Metabase хранится версия запроса БЕЗ этого длинного комментария: JDBC-драйвер ClickHouse падает
-- ("больше параметров, чем можем обработать") на комментарии с кавычками при подстановке параметров.
-- ВАЖНО — лимит Metabase 2000 строк на native-запрос (молча обрезает, LIMIT в SQL не обходит). Всего в
-- данных ~20 300 строк (3 600 с 2025-01), поэтому широкий период упрётся в лимит; сортировка от новых
-- месяцев к старым, чтобы терялись самые старые. Полную выгрузку брать через "Скачать результаты"
-- с узким периодом или несколькими фильтрами.
-- Пустой контрагент (23 строки, 2017 г.) и пустая номенклатура (735 строк) подписаны явно, не выбрасываются.

SELECT
    if(counterparty = '', 'Без контрагента', counterparty)   AS "Клиент юрлицо",
    if(nomenclature = '', 'Без номенклатуры', nomenclature)  AS "Продукция",
    month                                                    AS "Месяц",
    round(sum(amount), 2)                                    AS "Выручка без НДС, руб"
FROM realization_revenue
WHERE 1 = 1
    [[ AND {{company}} ]]
    [[ AND {{product}} ]]
    [[ AND {{period}} ]]
GROUP BY counterparty, nomenclature, month
ORDER BY month DESC, "Выручка без НДС, руб" DESC, counterparty, nomenclature
