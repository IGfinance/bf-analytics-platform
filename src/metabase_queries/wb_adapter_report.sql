-- Metabase: "Визуал - CloudSix - Отчет для адаптера WB" (id 43 на 2026-09-23).
-- Лежит на дашборде "01 Дашборд - CloudSix - Адаптеры" (id 2).
--
-- С 2026-09-23 карточка переделана из pivot-визуала в ПЛОСКУЮ широкую
-- выгрузку: одна строка = кабинет за месяц, показатели разложены по
-- столбцам в том же порядке и с той же нумерацией (01…17), что в отчётах
-- по артикулам. Колонка "Площадка" константна внутри карточки ('WB') и
-- нужна, чтобы выгрузки по WB и Ozon можно было сложить в одну таблицу —
-- ради этого же совпадает и порядок первых трёх колонок.
--
-- Формулы не дублируются: карточка читает готовые колонки Модели 49
-- через {{#49}} (см. wb_metrics_model.sql).
--
-- Фильтр "Кабинет" на дашборде привязан ЧЕРЕЗ ПЕРЕМЕННУЮ
-- ["variable", ["template-tag", "cabinet"]], а не через ["dimension", ...]:
-- у native SQL это единственный рабочий путь, dimension-таргет молча
-- перестаёт фильтровать (та же гочтя, что описана в
-- .claude/knowledge/architecture-standarts.md). До переделки карточка была
-- MBQL-пивотом, и таргет был dimension — при переходе маппинг на дашборде
-- пришлось переписать.
--
-- ПРАВКА 2026-09-27: добавлена колонка "06.01 Корректировки продаж" —
-- четвёртая составляющая "06 К перечислению за товар" (наряду с 03/04/05),
-- до этого она молча терялась (см. schema_wb_metrics_views_sku.sql). Номер
-- дочерний (06.01), а не новый верхнеуровневый, СПЕЦИАЛЬНО: карточка —
-- выгрузка для ВНЕШНЕГО адаптера, и сдвиг нумерации 07…17 сломал бы его
-- разбор. Конвенция дочерних номеров уже есть — 07.01/07.02 у логистики.
-- Если внешний адаптер к колонке готов, её можно поднять в верхний уровень
-- (как у Ozon, где корректировки — отдельная строка 06 перед 07).
--
-- Формально это карточка-Таблица на дашборде, то есть исключение из правила
-- "на дашборде только Визуалы" (см. architecture-standarts.md). Исключение
-- осознанное: карточка существует как выгрузка для внешнего адаптера, а не
-- как визуализация для чтения глазами. Имя оставлено с префиксом "Визуал -",
-- потому что это то, что реально выведено на дашборд.

-- ПРАВКА 2026-10-04: добавлен столбец «Бренд» после «Кабинета» (карточка 43). Источник —
-- wb_metrics_by_cabinet_brand_month_api: кабинет × бренд × месяц, бренд — строка отчёта, пустой = «Без бренда» без
-- перераспределения по артикулу. Сумма по брендам = прежняя строка кабинета (проверено
-- на данных, расхождение 0). Вьюхи генерирует scripts/gen_wb_metrics_brand_views.py.
-- Карточка читает вьюху напрямую, а не Модель 49 (бренда в модели нет, она не менялась); фильтр
-- month >= 2026-01-01 перенесён из Модели 49.

SELECT
    month                                                  AS "Месяц",
    cabinet                                                 AS "Кабинет",
    brand                                                   AS "Бренд",
    'WB'                                                     AS "Площадка",
    toFloat64(sales_qty)                                      AS "01 Кол-во продаж",
    toFloat64(sales_amount + spp_amount)                       AS "02 Продажи + СПП",
    toFloat64(sales_amount)                                     AS "03 Продажи",
    toFloat64(spp_amount)                                        AS "04 СПП",
    toFloat64(wb_commission)                                      AS "05 Комиссия ВБ",
    toFloat64(payable_for_goods)                                   AS "06 К перечислению за товар",
    toFloat64(sales_corrections)                                    AS "06.01 Корректировки продаж",
    toFloat64(logistics_direct + logistics_reverse)                  AS "07 Логистика",
    toFloat64(logistics_direct)                                       AS "07.01 Логистика прямая",
    toFloat64(logistics_reverse)                                       AS "07.02 Логистика обратная",
    toFloat64(fines)                                                    AS "08 Штрафы",
    toFloat64(commission_correction)                                     AS "09 Доплаты",
    toFloat64(storage_cost)                                               AS "10 Хранение",
    toFloat64(acceptance_cost)                                             AS "11 Платная приемка",
    toFloat64(deductions)                                                   AS "12 Удержание",
    toFloat64(wibes_discount)                                                AS "13 Скидка Wibes",
    toFloat64(promotion_cost)                                                 AS "14 Продвижение WB",
    toFloat64(payable_total)                                                   AS "15 К перечислению",
    toFloat64(cogs)                                                             AS "16 Себестоимость",
    toFloat64(gross_profit)                                                      AS "17 Валовая прибыль"
FROM wb_metrics_by_cabinet_brand_month_api
-- Загружен только 2026 год (решение владельца 2026-09-28): строки, датированные концом 2025 внутри
-- отчётов 2026, — огрызок периода, а не данные (как в Модели 49, которую эта карточка раньше читала).
WHERE month >= toDate('2026-01-01')
[[AND cabinet = {{cabinet}}]]
ORDER BY month, cabinet, brand
