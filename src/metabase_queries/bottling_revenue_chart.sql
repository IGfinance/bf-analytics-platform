-- Metabase: "Визуал - Bottling - Выручка по месяцам" (график).
-- Дашборд: "Дашборд - Bottling - Выручка".
--
-- Схлопывает модель (грейн месяц x контрагент x номенклатура) до
-- месяца — читает {{#205}} (Модель - Bottling - Выручка по месяцам),
-- формулу не дублирует.

SELECT
    "Месяц"              AS "Месяц",
    sum("Выручка")       AS "Выручка"
FROM {{#205}}
GROUP BY "Месяц"
ORDER BY "Месяц"
