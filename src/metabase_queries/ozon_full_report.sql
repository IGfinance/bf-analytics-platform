-- Metabase: native SQL карточки "Таблица - Полный отчет Ozon" (id 63 на
-- 2026-09-08) — аналог "Таблица - Полный отчет Wb" (id 42, см.
-- wb_metrics_by_month.sql). Разворачивает "Модель - Ozon метрики по
-- кабинету и месяцу" (id 62, см. ozon_metrics_model.sql) в long-формат
-- (строка = метрика), нужный для pivot table в Metabase.
--
-- "Визуал - Полный отчет Ozon" (id 64) строит breakout по metric/month
-- поверх этой карточки — та же схема, что "Визуал - Полный отчет Wb" (id 43).
-- Оба визуала (WB и Ozon) размещены на дашборде id 2 с общим фильтром
-- "Кабинет", который мапится на обе карточки одновременно — выбор кабинета,
-- которого нет на одной из площадок (например WB-кабинет ARB для Ozon-
-- панели), корректно даёт пустой результат на той панели, а не ошибку.
--
-- {{#62}} — Metabase-плейсхолдер card-ссылки на модель, не переносимый SQL
-- (id поменяется, если модель пересоздать — см. пояснение в
-- wb_metrics_by_month.sql).
--
-- В отличие от WB-карточки, здесь НЕТ вычисляемых комбинаций метрик
-- ("Продажи + СПП" и т.п.) — "Выручка + СПП" уже отдельная колонка в
-- самой модели (sales_with_spp в ozon_metrics_by_cabinet_month), считать
-- её здесь заново не нужно.

SELECT * FROM (
SELECT "Месяц" AS month, "Кабинет" AS cabinet, '01 Кол-во продаж' AS metric, toFloat64("Кол-во продаж") AS value FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '02 Выручка + СПП', toFloat64("Выручка + СПП") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '03 Выручка', toFloat64("Выручка") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '04 СПП', toFloat64("СПП") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '05 Комиссия', toFloat64("Комиссия") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '06 Корректировки, брак, потери и возвраты', toFloat64("Корректировки, брак, потери и возвраты") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '07 К перечислению за товар', toFloat64("К перечислению за товар") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '08 Логистика', toFloat64("Логистика") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '09 Последняя миля', toFloat64("Последняя миля") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '10 Штрафы', toFloat64("Штрафы") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '11 Доплаты', toFloat64("Доплаты") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '12 Хранение на складе', toFloat64("Хранение на складе") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '13 Продвижение', toFloat64("Продвижение") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '14 Прочие начисления', toFloat64("Прочие начисления") FROM {{#62}}
UNION ALL SELECT "Месяц", "Кабинет", '15 Выручка к перечислению', toFloat64("Выручка к перечислению") FROM {{#62}}
)
ORDER BY month, cabinet, metric
