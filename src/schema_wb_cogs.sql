-- Себестоимость товара по неделям — ручная выгрузка .xlsx ("СС <проект> от <дата>.xlsx",
-- см. wb_cogs_core.py). Одна строка = артикул × неделя × себестоимость единицы.
--
-- Таблица ПРОЕКТНАЯ, без колонки cabinet — это осознанно, а не упущение:
-- в самом файле разреза по кабинетам нет (один лист "CC общ": артикулы в
-- строках, недели в столбцах), а проверка по факту на данных 2026-09-23
-- показала, что артикулы файла бьются сразу с несколькими кабинетами
-- проекта (Hauser 99% проданных единиц покрыто, NoxLab 99%, CloudSix 97%,
-- INOVO 97%) — то есть это справочник закупочной цены на уровне проекта,
-- а один и тот же товар может продаваться через разные кабинеты по той же
-- себестоимости. Если когда-нибудь появится файл с разной себестоимостью
-- одного артикула по кабинетам — сюда добавляется cabinet в ORDER BY,
-- и join в wb_metrics_by_sku_month расширяется на третий ключ.
--
-- sku хранится в нижнем регистре — это ключ join'а с wb_reports.
-- supplier_article: в файле артикулы записаны как "Aero_10L", а в отчётах
-- WB — как "aero_10l" (проверено 2026-09-23: при точном сравнении сходилось
-- 19 артикулов из 415, при регистронезависимом — 225). Исходное написание
-- из файла сохраняется в sku_source, чтобы можно было вернуться к первоисточнику.
--
-- Недели — понедельник-воскресенье, как в самом файле (проверено: все 40
-- недель начинаются с понедельника, идут без разрывов и все по 7 дней).
-- Нумерация недель из файла (week_label) хранится как строка и НЕ участвует
-- в join'е: в файле первая неделя названа "53" (это 29.12.2025-04.01.2026,
-- т.е. хвост нумерации 2025 года), дальше идут 2..40 — сквозной нумерации
-- по годам нет, источник истины для сопоставления — даты, не номер.

CREATE TABLE IF NOT EXISTS wb_cogs_weekly
(
    sku          String,     -- артикул в нижнем регистре — ключ join'а с wb_reports.supplier_article
    week_start   Date,       -- понедельник недели
    week_end     Date,       -- воскресенье той же недели
    week_label   String,     -- номер недели как он написан в файле ("53", "2", ...)
    unit_cost    Float64,    -- себестоимость ОДНОЙ единицы товара, ₽
    sku_source   String,     -- исходное написание артикула из файла
    source_file  String,     -- имя файла-источника, чтобы было видно, из какой выгрузки цифра
    loaded_at    DateTime DEFAULT now()
)
ENGINE = ReplacingMergeTree(loaded_at)
ORDER BY (sku, week_start);

ALTER TABLE wb_cogs_weekly COMMENT COLUMN sku 'Артикул продавца в НИЖНЕМ регистре — именно в таком виде сопоставляется с lowerUTF8(trim(supplier_article)) из wb_reports. Регистр в файле и в отчётах WB отличается, сравнивать напрямую нельзя.';
ALTER TABLE wb_cogs_weekly COMMENT COLUMN week_start 'Понедельник недели, к которой относится себестоимость. Сопоставление с продажей идёт по toMonday(sale_date) из wb_reports, а НЕ по периоду отчёта WB.';
ALTER TABLE wb_cogs_weekly COMMENT COLUMN unit_cost 'Себестоимость ОДНОЙ единицы товара в рублях. Чтобы получить себестоимость продаж, умножается на количество (продажи минус возвраты) — см. cogs в wb_metrics_by_sku_month.';
ALTER TABLE wb_cogs_weekly COMMENT COLUMN week_label 'Номер недели из шапки файла как строка. Справочное поле: в файле нумерация не сквозная (первая неделя названа ''53''), для сопоставления используются даты.';
