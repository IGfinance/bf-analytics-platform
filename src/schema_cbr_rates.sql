-- Курсы ЦБ РФ к рублю. Справочник общий, не привязан к WB и к одной валюте:
-- сейчас нужен сом (KGS) для кабинета NoxLab, завтра может понадобиться
-- тенге или лира под другой кабинет.
--
-- ЗАЧЕМ. NoxLab — киргизский кабинет, WB отдаёт его отчёты в СОМАХ (в API
-- это видно по полю currency = 'KGS', у остальных семи кабинетов 'RUB').
-- До 2026-09-28 мы этого не учитывали и складывали сомы с рублями. Именно
-- отсюда бралось «необъяснимое» расхождение NoxLab во внешней сверке
-- (Сверка_WB_дашборд_vs_адаптеры_25_09_26.xlsx): все денежные показатели
-- отличались на 12-16%, коэффициент плавал по месяцам 0.834-0.919 — это и
-- был курс сома, а не ошибка данных.
--
-- НОМИНАЛ. ЦБ котирует сом за 100 единиц (Nominal=100, значение ~90 руб).
-- Колонка value — как отдаёт ЦБ, rate — уже пересчитанный курс за ОДНУ
-- единицу валюты. В расчётах используйте rate, иначе ошибётесь в 100 раз.
--
-- ВЫХОДНЫЕ И ПРАЗДНИКИ. ЦБ публикует курс не каждый календарный день: за
-- 2026-01-01..09-28 приходит 180 значений на ~270 дней. Поэтому потребители
-- берут курс ASOF-джойном («последний известный на эту дату»), а не точным
-- совпадением дат — см. schema_wb_api_as_reports.sql. Точное совпадение
-- молча потеряло бы все операции выходного дня.
--
-- ИСТОЧНИК: https://www.cbr.ru/scripts/XML_dynamic.asp — загрузка
-- src/ingest_cbr_rates.py. Курсы ЦБ задним числом не меняются, поэтому
-- ReplacingMergeTree по (currency, rate_date) и повторная загрузка того же
-- периода безопасна.

CREATE TABLE IF NOT EXISTS cbr_rates
(
    currency     LowCardinality(String),  -- ISO-код, напр. 'KGS'
    rate_date    Date,                     -- дата, на которую ЦБ установил курс
    cbr_code     String,                   -- внутренний код ЦБ, напр. 'R01370'
    nominal      UInt32,                   -- за сколько единиц валюты дан value
    value        Float64,                  -- рублей за nominal единиц, как у ЦБ
    rate         Float64,                  -- рублей за ОДНУ единицу = value / nominal
    loaded_at    DateTime DEFAULT now()
)
ENGINE = ReplacingMergeTree(loaded_at)
ORDER BY (currency, rate_date);

ALTER TABLE cbr_rates COMMENT COLUMN currency 'ISO-код валюты (KGS, KZT, ...). Сопоставляется с полем currency в wb_api_realization.';
ALTER TABLE cbr_rates COMMENT COLUMN rate_date 'Дата, НА КОТОРУЮ ЦБ установил курс. Публикуется не каждый день (выходные, праздники) — потребители берут последний известный курс ASOF-джойном, а не точным совпадением.';
ALTER TABLE cbr_rates COMMENT COLUMN nominal 'За сколько единиц валюты указан value. У сома 100 — ЦБ котирует рубли за 100 сомов.';
ALTER TABLE cbr_rates COMMENT COLUMN value 'Рублей за nominal единиц валюты — ровно как отдаёт ЦБ, без пересчёта.';
ALTER TABLE cbr_rates COMMENT COLUMN rate 'Рублей за ОДНУ единицу валюты = value / nominal. В расчётах используйте ЭТУ колонку: value без деления на номинал даст ошибку в 100 раз.';
